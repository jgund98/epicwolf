// Bakes the hero's big words (IMPOSSIBLE / TO IGNORE.) into outline paths for the
// canvas mask in components/home/Hero.tsx. Two Archivo 900 instances, matching
// .hero-word: wdth 125 on desktop, wdth 82 on phones. Paths are font-independent,
// so every browser (Safari included, which can't set a width axis on canvas text)
// cuts exactly the same letters the page lays out.
import fs from "fs"
import { createRequire } from "module"
const require = createRequire("C:/Users/Lucky/find-tool-plan-nextJS/package.json")
const fontkit = require("fontkit")

const LINES = ["IMPOSSIBLE", "TO IGNORE."]
const VARIANTS = { wide: { file: "archivo-900-125", track: -0.045 }, narrow: { file: "archivo-900-82", track: -0.03 } }
const f = (n) => String(+n.toFixed(1))

const out = {}
for (const [key, v] of Object.entries(VARIANTS)) {
  const font = fontkit.openSync(`raw/font/${v.file}.ttf`)
  const k = 1000 / font.unitsPerEm
  const lines = LINES.map((text) => {
    const run = font.layout(text)
    let x = 0
    const parts = []
    run.glyphs.forEach((g, i) => {
      const d = g.path.scale(k, -k).translate(x, 0).toSVG().replace(/-?\d+(\.\d+)?/g, (m) => f(+m))
      parts.push(d)
      x += run.positions[i].xAdvance * k + v.track * 1000
    })
    return { d: parts.join(""), adv: +x.toFixed(1) }
  })
  const I = font.glyphForCodePoint(73)
  out[key] = {
    lines,
    stem: { x0: +(I.bbox.minX * k).toFixed(1), x1: +(I.bbox.maxX * k).toFixed(1), cap: +(I.bbox.maxY * k).toFixed(1) },
  }
}

fs.writeFileSync(
  "components/home/heroMask.ts",
  `// Generated by scripts/build-hero-mask.mjs. Do not edit by hand.
// Units: 1000 per em, y down, baseline at 0, pen starting at 0. adv includes letter-spacing.
export type MaskLine = { d: string; adv: number }
export type MaskFace = { lines: MaskLine[]; stem: { x0: number; x1: number; cap: number } }
export const HERO_MASK: Record<"wide" | "narrow", MaskFace> = ${JSON.stringify(out)}
`
)
