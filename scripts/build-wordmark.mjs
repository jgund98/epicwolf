// Bakes the lowercase "epicwolf." wordmark (Archivo 900 wdth 112 + the wolf-ear w)
// into components/brand/wordmark.ts as plain path data. Re-run after tuning the w.
import fs from "fs"
import { load } from "./wordmark-study.mjs"
import { wolfW } from "./wordmark-lab.mjs"

const font = load("archivo-900-112")
const EAR = { J: 400, T: 600, tip: 352, N: 400, r: 46 }
const TRACK = -50 // font units (1000 per em)

const w = wolfW(EAR)
const gl = (ch) => font.glyphForCodePoint(ch.codePointAt(0))
const ASC = Math.ceil(Math.max(gl("l").bbox.maxY, gl("f").bbox.maxY, gl("i").bbox.maxY, EAR.T)) // top of the tallest mark
const DESC = Math.ceil(-gl("p").bbox.minY)
const H = ASC + DESC
const f = (n) => +n.toFixed(1)

/** Glyph outline shifted to x, y-down with the baseline at ASC. */
function glyph(ch, x) {
  return gl(ch).path.scale(1, -1).translate(x, ASC).toSVG().replace(/-?\d+\.\d+/g, (m) => String(f(+m)))
}
function wPath(x) {
  const P = (px, py) => `${f(x + px)} ${f(ASC - py)}`
  return w.segs.map((g) => (g[0] === "Q" ? `Q${P(g[1], g[2])} ${P(g[3], g[4])}` : g[0] + P(g[1], g[2]))).join("") + "Z"
}
function word(text, x0 = 0) {
  let x = x0
  const letters = []
  for (const ch of text) {
    const adv = ch === "w" ? w.adv : gl(ch).advanceWidth
    letters.push({ ch, d: ch === "w" ? wPath(x) : glyph(ch, x) })
    x += adv + TRACK
  }
  return { letters, end: x - TRACK }
}
// Glyphs carry side bearings; trim the lockup to the ink.
const first = gl("e").bbox.minX
const full = word("epicwolf", -first)
const R = 118
const cx = full.end + 40 + R
const dot = `M${f(cx - R)} ${ASC - R}a${R} ${R} 0 1 0 ${2 * R} 0a${R} ${R} 0 1 0 ${-2 * R} 0Z`
const WM_W = Math.ceil(cx + R)

const epic = word("epic", -first)
const wolf = word("wolf", -w.segs.reduce((m, g) => Math.min(m, g[1]), 1e9))
const inkRight = (text) => {
  const last = text.at(-1)
  return gl(last).bbox.maxX
}
const epicW = Math.ceil(epic.end - gl("c").advanceWidth + inkRight("c"))
const wolfW_ = Math.ceil(wolf.end - gl("f").advanceWidth + inkRight("f"))

// The mark: the w alone, ears and all, in a square with its visual center at the middle.
const MARK_S = 1100
const mx = (MARK_S - w.adv) / 2
const my = (MARK_S - EAR.T) / 2
const mark = w.segs.map((g) => {
  const P = (px, py) => `${f(mx + px)} ${f(my + EAR.T - py)}`
  return g[0] === "Q" ? `Q${P(g[1], g[2])} ${P(g[3], g[4])}` : g[0] + P(g[1], g[2])
}).join("") + "Z"

const out = `// Generated by scripts/build-wordmark.mjs. Do not edit by hand.
// "epicwolf." in Archivo 900 (wdth 112), tracked tight, with the wolf-ear w and a round period.
// Units: 1000 per em, y down, baseline at WM_BASE.

export const WM_W = ${WM_W}
export const WM_H = ${H}
export const WM_BASE = ${ASC}
/** Letters of "epicwolf" in order, absolute paths inside 0 0 WM_W WM_H. */
export const WM_LETTERS: { ch: string; d: string }[] = ${JSON.stringify(full.letters, null, 2)}
/** The period, drawn separately so it can carry the accent color. */
export const WM_DOT = ${JSON.stringify(dot)}

/** The two words on their own, same scale and baseline, for the partners chapter. */
export const WM_EPIC = { w: ${epicW}, letters: ${JSON.stringify(epic.letters)} }
export const WM_WOLF = { w: ${wolfW_}, letters: ${JSON.stringify(wolf.letters)} }

/** The mark: the wolf-ear w, centered in a ${MARK_S} square. */
export const MARK_SIZE = ${MARK_S}
export const MARK_D = ${JSON.stringify(mark)}
`
fs.writeFileSync("components/brand/wordmark.ts", out)
console.log({ WM_W, H, ASC, DESC, epicW, wolfW: wolfW_ })
